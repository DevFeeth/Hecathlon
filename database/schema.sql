
    create table authority (
        id integer generated by default as identity,
        name varchar(255),
        primary key (id)
    );

    create table order_line (
        quantity integer not null,
        unit_price numeric(10,2) not null,
        id bigint generated by default as identity,
        order_id bigint not null,
        brand varchar(255),
        image varchar(255),
        product_id varchar(255) not null,
        product_name varchar(255) not null,
        size varchar(255),
        primary key (id)
    );

    create table orders (
        delivery_cost numeric(10,2) not null,
        subtotal numeric(10,2) not null,
        total numeric(10,2) not null,
        date timestamp(6) not null,
        id bigint generated by default as identity,
        paid_at timestamp(6),
        status_date timestamp(6),
        status varchar(20) not null check ((status in ('PENDING_PAYMENT','CONFIRMED','PREPARED','SHIPPED','DELIVERED'))),
        payment_reference varchar(64),
        address varchar(255),
        address_complement varchar(255),
        city varchar(255),
        country varchar(255),
        customer_email varchar(255) not null,
        delivery_mode varchar(255) not null check ((delivery_mode in ('HOME','STORE'))),
        email varchar(255) not null,
        first_name varchar(255) not null,
        last_name varchar(255) not null,
        phone varchar(255) not null,
        postal_code varchar(255),
        primary key (id)
    );

    create table product (
        best_seller boolean not null,
        featured boolean not null,
        highlighted boolean not null,
        old_price numeric(10,2),
        position integer not null,
        price numeric(10,2) not null,
        rating float(53) not null,
        review_count integer not null,
        sport_id varchar(30) not null,
        type_id varchar(30) not null,
        id varchar(40) not null,
        brand varchar(60) not null,
        name varchar(120) not null,
        short_description varchar(120),
        description varchar(1000),
        image varchar(255),
        primary key (id)
    );

    create table product_size (
        position integer not null check ((position>=0)),
        size varchar(10) not null,
        product_id varchar(40) not null,
        primary key (position, product_id)
    );

    create table product_type (
        position integer not null,
        id varchar(30) not null,
        name_en varchar(60) not null,
        name_fr varchar(60) not null,
        primary key (id)
    );

    create table sport (
        position integer not null,
        id varchar(30) not null,
        name_en varchar(60) not null,
        name_fr varchar(60) not null,
        tagline_en varchar(120),
        tagline_fr varchar(120),
        description_en varchar(500),
        description_fr varchar(500),
        image varchar(255),
        primary key (id)
    );

    create table "user" (
        account_non_expired boolean,
        account_non_locked boolean,
        created_at date,
        credentials_non_expired boolean,
        enabled boolean,
        newsletter boolean,
        address varchar(255),
        address_complement varchar(255),
        city varchar(255),
        country varchar(255),
        email varchar(255) not null,
        first_name varchar(255) not null,
        last_name varchar(255) not null,
        password varchar(255) not null,
        phone varchar(255),
        postal_code varchar(255),
        primary key (email)
    );

    create table user_authority (
        authority_id integer not null,
        user_email varchar(255) not null
    );

